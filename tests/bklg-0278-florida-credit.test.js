const test=require('node:test')
const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const source=fs.readFileSync(path.join(__dirname,'../assets/js/log-dashboard-entry-v5.js'),'utf8')
const start=source.indexOf('  function floridaCreditMarkup(d){')
const end=source.indexOf('  function vehicleMarkup(v){',start)
assert.ok(start>=0&&end>start,'Florida credit rendering helper is present')
const markup=new Function(source.slice(start,end)+'; return floridaCreditMarkup')()
test('excluded Florida learner minutes show a distinct warning without illegal-driving allegation',()=>{
 const html=markup({florida_credit:{license_stage:'LEARNER',prohibited_minutes:15,pending_minutes:0}})
 assert.match(html,/15 min excluded from qualifying credit/)
 assert.match(html,/Original drive retained/)
 assert.doesNotMatch(html,/illegal|violation/i)
})
test('pending evidence is not labeled prohibited',()=>{
 const html=markup({florida_credit:{license_stage:'LEARNER',prohibited_minutes:0,pending_minutes:30}})
 assert.match(html,/review pending for 30 min/)
 assert.doesNotMatch(html,/excluded from qualifying credit/)
})
test('other jurisdictions and no evaluation remain unchanged',()=>{
 assert.equal(markup({florida_credit:null}),'')
 assert.equal(markup({florida_credit:{license_stage:'STATE_NEUTRAL',prohibited_minutes:30}}),'')
})
test('credit quantities are numeric and cannot inject HTML',()=>{
 const html=markup({florida_credit:{license_stage:'LEARNER',prohibited_minutes:'<svg onload=alert(1)>',pending_minutes:0}})
 assert.equal(html,'')
})

test('actual supervising adult must attest to all four explicit facts',()=>{
 const snippet=source.slice(source.indexOf('  function floridaSupervisorAttestationMarkup(d){'),source.indexOf('  function vehicleMarkup(v){'))
 const markup=new Function('esc','currentDriver',snippet+';return floridaSupervisorAttestationMarkup')(value=>String(value),()=>({license_stage:'LEARNER'}))
 assert.equal(markup({fl_can_attest:false,florida_credit:{pending_minutes:15}}),'')
 const html=markup({id:'drive-1',drive_revision:2,fl_can_attest:true,florida_credit:{pending_minutes:15}})
 assert.match(html,/age_at_least_21/)
 assert.match(html,/valid_driver_license/)
 assert.match(html,/nearest_right_seat/)
 assert.match(html,/declarant_supervised_drive/)
 assert.match(html,/Only the adult who actually supervised this drive/)
})
test('Florida dashboard details use authenticated drive-ops rather than the legacy driver API',()=>{
 assert.match(source,/action:'fl_credit_context'/)
 assert.match(source,/session\.access_token/)
 assert.match(source,/floridaCreditCache\.clear\(\)/)
 assert.match(source,/modelEpoch/)
 assert.match(source,/action:'attest_fl_supervision'/)
 assert.match(source,/expected_revision:selected\.drive_revision/)
})

test('only a linked grown-up receives a direct-work commute declaration',()=>{
 const snippet=source.slice(source.indexOf('  function floridaWorkCommuteMarkup(d){'),source.indexOf('  function vehicleMarkup(v){'))
 const markup=new Function('esc',snippet+';return floridaWorkCommuteMarkup')(value=>String(value))
 assert.equal(markup({fl_can_confirm_work:false,florida_credit:{pending_minutes:15}}),'')
 const html=markup({id:'drive-2',drive_revision:4,fl_can_confirm_work:true,florida_credit:{pending_minutes:15}})
 assert.match(html,/direct_to_from_work/)
 assert.match(html,/adult_confirms_facts/)
 assert.match(html,/to or from the driver's work/)
 assert.match(source,/action:'attest_fl_work_commute'/)
 assert.match(source,/expected_revision:selected\.drive_revision/)
})

test('missing evaluation remains visibly pending with recovery declaration available',()=>{
 const creditSnippet=source.slice(source.indexOf('  function floridaCreditMarkup(d){'),source.indexOf('  function floridaSupervisorAttestationMarkup(d){'))
 const credit=new Function(creditSnippet+';return floridaCreditMarkup')()
 const supervisorSnippet=source.slice(source.indexOf('  function floridaSupervisorAttestationMarkup(d){'),source.indexOf('  function floridaWorkCommuteMarkup(d){'))
 const supervisor=new Function('esc','currentDriver',supervisorSnippet+';return floridaSupervisorAttestationMarkup')(v=>String(v),()=>({license_stage:'LEARNER'}))
 const workSnippet=source.slice(source.indexOf('  function floridaWorkCommuteMarkup(d){'),source.indexOf('  function vehicleMarkup(v){'))
 const work=new Function('esc',workSnippet+';return floridaWorkCommuteMarkup')(v=>String(v))
 const noEvidence={id:'d-1',drive_revision:3,fl_credit_missing:true,florida_credit:null,
   fl_can_attest:true,fl_can_confirm_work:true}
 assert.match(credit(noEvidence),/credit evaluation is pending/i)
 assert.match(supervisor(noEvidence),/Confirm I supervised this drive/)
 assert.match(work(noEvidence),/Confirm direct travel to or from work/)
 assert.equal(credit({florida_credit:null}), '')
})

test('Florida supervision form asks learner-only right-seat declaration',()=>{
 const snippet=source.slice(source.indexOf('  function floridaSupervisorAttestationMarkup(d){'),source.indexOf('  function floridaWorkCommuteMarkup(d){'))
 const build=new Function('esc','currentDriver',snippet+';return floridaSupervisorAttestationMarkup')
 const draft={id:'drive-1',drive_revision:2,fl_can_attest:true,florida_credit:{pending_minutes:15}}
 const learner=build(v=>String(v),()=>({license_stage:'LEARNER'}))(draft)
 const intermediate=build(v=>String(v),()=>({license_stage:'INTERMEDIATE'}))(draft)
 assert.match(learner,/nearest_right_seat/)
 assert.doesNotMatch(intermediate,/nearest_right_seat/)
 assert.match(intermediate,/age_at_least_21/)
 assert.match(intermediate,/valid_driver_license/)
 assert.match(source,/nearest_right_seat:learner/)
})
